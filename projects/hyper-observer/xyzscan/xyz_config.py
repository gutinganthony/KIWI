# L3 每人要打一次 userFills（權重可達 120），所以倖存者上限就是 L3 的成本上限。
# 60 個 → 約 7,200 權重，配 0.5s 間隔約 30 秒送完，遠低於 1,200 權重／分鐘的限額
# （fetch.py 的 sleep 已把速率壓在安全區）。
