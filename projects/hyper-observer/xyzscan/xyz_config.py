# ---------------------------------------------------------------------------
# L1：母體取得（公開 trades 頻道）
# ---------------------------------------------------------------------------
WS_URL = "wss://api.hyperliquid.xyz/ws"
WS_TIMEOUT_SEC = 20
WS_COLLECT_SEC = 420      # 收集 7 分鐘（GitHub job 上限 6 小時，這裡刻意短）
WS_MAX_COINS = 40         # 一次最多訂閱幾個合約（訂閱過多會被斷線）
# WS 收到的地址數少於此值 → 加上排行榜備援母體（避免 xyz 冷清時空手而回）
L1_MIN_ADDRESSES = 40
# L2 要對每個地址各發一個請求（權重 2），母體上限直接決定成本：
# 600 個 → 1,200 權重，配合 fetch 的 0.5s 間隔約 5 分鐘。
L1_MAX_ADDRESSES = 600
LEADERBOARD_FALLBACK_LIMIT = 200

# ---------------------------------------------------------------------------
# L2：便宜篩選
# ---------------------------------------------------------------------------
# xyz 帳戶淨值門檻。動機：跟單者要跟的是「有資本紀律的人」，$10k 以下的帳戶
# 就算勝率漂亮也可能是幾十筆小單的運氣，且他的部位大小對我們沒有參考價值。
L2_MIN_ACCOUNT_VALUE = 25_000.0
# L3 每人要分頁抓近 30 天成交（每頁權重 20、最多 FILL_PAGE_CAP 頁），
# 所以倖存者上限就是 L3 的成本上限：60 × 4 頁 × 20 = 4,800 權重，
# 配 fetch.py 的 0.5s 間隔約 2 分鐘送完，遠低於 1,200 權重／分鐘的限額。
L2_MAX_SURVIVORS = 60

# ---------------------------------------------------------------------------
# L3：成交樣本取得（userFillsByTime 分頁）
# ---------------------------------------------------------------------------
# 為什麼不用 userFills：它只回**最近 2000 筆**。第一版掃描的 54 個候選全部觸頂，
# 活躍跨度全被算成 0～1 天，整批以「樣本截斷／跨度不足」淘汰——等於什麼都沒驗證到。
# 用 userFillsByTime 指定時間窗並分頁，才拿得到真正的 30 天樣本。
FILL_WINDOW_DAYS = 30
# 分頁上限。30 天內成交超過 PAGE_CAP × 2000 筆＝真做市／高頻型，本來就該淘汰，
# 所以觸及上限直接當硬性缺陷，不再繼續往下抓。
# 成本：每頁權重 20，60 個倖存者 × 最多 4 頁 = 4,800 權重（限額 1,200 權重／分鐘，
# fetch.py 的 0.5s 間隔已把速率壓在安全區）。
FILL_PAGE_CAP = 4

# ---------------------------------------------------------------------------
# L3：winner 判準
# ---------------------------------------------------------------------------
MIN_CLOSED_FILLS = 30      # 平倉樣本數下限（低於此值勝率是噪音）
MIN_SPAN_DAYS = 14         # 活躍跨度
MIN_NET_PNL = 5_000.0      # xyz 損益下限（已實現＋未實現，見下方未實現說明）
MIN_PROFIT_FACTOR = 1.3    # 與 config.CONSISTENT_MIN_PROFIT_FACTOR 一致（地板，非主關卡）

# ---------------------------------------------------------------------------
# 賠率（平均獲利 ÷ 平均虧損）——本判準的主關卡
# ---------------------------------------------------------------------------
# 目標型態：**大賺、小賺、小虧，避免大虧**。量化後就是「賠率顯著大於 1」。
MIN_WIN_TO_LOSS = 2.0       # 平均獲利至少是平均虧損的 2 倍
STRONG_WIN_TO_LOSS = 3.0    # 達 3 倍在報告標 ⭐（偏好，不是門檻）

# 勝率下限：從 0.55 降到 0.40。理由是數學上的耦合——
#   獲利因子 = 勝率/(1-勝率) × 平均獲利/平均虧損
# 同時要求「高勝率」與「高賠率」等於要求一個極端值，會把最會賺的人擋掉：
# 2026-07-30 第二版掃描的 0x6691da5f 勝率只有 46.2%，卻靠賠率 3.67 淨賺 $53k，
# 正是「小虧多次、大賺幾次」的健康型態。原本 55% 是照「想找高勝率錢包」的直覺
# 設的，不是從資料推出來的。現在勝率只用來排除樂透型（贏一次撐全場）。
MIN_WIN_RATE = 0.40

# 單筆最大虧損佔毛利上限——直接對應「避免大虧」。
# 一筆虧損就吃掉三分之一以上毛利＝風險控制有破口，即使總帳還是賺的。
# 非硬性缺陷：只差這一項會落在 near_miss（看得見，不會被靜默丟掉）。
MAX_WORST_LOSS_SHARE = 0.35

MAX_TOP_TRADE_SHARE = 0.50  # 單筆最大獲利占毛利上限（擋一次好運）
MAX_LIQUIDATIONS = 3        # 強平次數上限（>= 此值直接淘汰）
MAX_IDLE_DAYS = 10          # 最後成交距今天數上限（停手的人跟不了）

# ---------------------------------------------------------------------------
# 未實現損益（補「從不認賠」的盲點）
# ---------------------------------------------------------------------------
# 只算 closedPnl 有個致命盲點：**一個從不認賠的人，已實現數字會完美無瑕**。
# 2026-07-30 第二版的 0x2171b50b 勝率 100%、獲利因子 999——但他有一個名目 $383k
# 的部位掛在 $101k 淨值上（約 3.8 倍槓桿）。那個部位若深度套牢，$63k 的「已實現
# 獲利」就是假象。所以：
#   1) 判定改用 **總損益 = 已實現 + 未實現**，不再只看已實現；
#   2) 未實現虧損吃掉超過此比例的已實現獲利 → 硬性淘汰（典型的抱虧不認）。
MAX_UNREALIZED_LOSS_SHARE = 0.50

