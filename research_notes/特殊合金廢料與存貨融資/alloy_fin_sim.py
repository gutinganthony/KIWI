print("\n== 存貨融資：2,000 萬元分成 N 筆，各筆獨立違約(A) ==")
import math
def dist(n, p, y, lgd, total=2000):
    per = total/n
    exp = total*((1-p)*y - p*lgd)
    # 至少一筆違約的機率與最壞兩筆違約
    p_any = 1-(1-p)**n
    one = total*y - per*(y+lgd)      # 剛好一筆違約的年損益
    return exp, p_any, one
print("  筆數  年收益  違約率  損失率 | 期望年損益(萬)  至少一筆違約機率  剛好一筆違約時年損益(萬)")
for n in (1, 4, 10):
    for y,p,lgd in ((0.10,0.05,0.6),(0.12,0.05,0.6),(0.12,0.10,0.6)):
        e,pa,one = dist(n,p,y,lgd)
        print(f"   {n:>2}    {y:4.0%}    {p:4.0%}    {lgd:4.0%}  |   {e:7.0f}        {pa:6.1%}            {one:7.0f}")
